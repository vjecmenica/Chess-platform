import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { Chess } from 'chess.js';
import { normalizedPositionKey } from '../dist/index.js';

const directory = process.argv[2];
if (!directory) throw new Error('Provide the directory containing the pinned a.tsv through e.tsv files.');

const records = new Map();
let maxPly = 0;
for (const volume of 'abcde') {
  const tsv = await readFile(resolve(directory, volume + '.tsv'), 'utf8');
  for (const row of tsv.trimEnd().split(/\r?\n/).slice(1)) {
    const [eco, name, pgn] = row.split('\t');
    const chess = new Chess();
    chess.loadPgn(pgn + ' *', { strict: true });
    const depth = chess.history().length;
    const key = normalizedPositionKey(chess.fen());
    const previous = records.get(key);
    const label = `${eco}\t${name}`;
    if (!previous || depth > previous.depth || depth === previous.depth && label < previous.label)
      records.set(key, { depth, label });
    maxPly = Math.max(maxPly, depth);
  }
}

const data = [...records.keys()].sort().map(key => {
  const { depth, label } = records.get(key);
  return JSON.stringify(`${key}\t${depth}\t${label}\n`);
});
await writeFile(new URL('../src/opening-data.ts', import.meta.url),
  `// Generated by scripts/generate-openings.mjs. Source and license: see openings/README.md.\n`
  + `export const maxOpeningPly = ${maxPly};\nexport const openingData: string = [\n  ${data.join(',\n  ')}\n].join('');\n`);
console.log(`${records.size} named positions, up to ${maxPly} plies`);
